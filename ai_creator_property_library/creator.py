class Creator:
    """
    创造者：整合 AI 后端、属性验证、造物记录

    使用方式：
        creator = Creator()
        result = creator.create(["不可伪造", "远程连接", "身份验证"])
        print(result["description"])
        print(creator.get_emergent_report(result))
    """

    def __init__(self, ai_backend=None, property_library: Dict = None):
        self.validator = PropertyValidator(property_library or PROPERTY_LIBRARY)
        self.ai = ai_backend or SimulatedAI()
        self.history: List[Dict] = []

    def create(self, properties: List[str], iterations: int = 1) -> Dict:
        """
        创造一种新造物

        Args:
            properties: 指定的核心属性列表（至少1条）
            iterations: 迭代次数（多次创造可能得到不同涌现结果）

        Returns:
            造物结果字典
        """
        if not properties:
            raise ValueError("至少需要指定 1 个属性")

        if iterations < 1:
            iterations = 1

        best_result = None
        for _ in range(iterations):
            result = self.ai.create(properties)
            validated = self._validate(result)
            result["validation"] = validated

            if validated["all_core_satisfied"]:
                best_result = result
                break
            best_result = result

        self.history.append(best_result)
        return best_result

    def _validate(self, result: Dict) -> Dict:
        """验证造物是否满足核心属性"""
        text = result.get("description", "") + " " + result.get("mechanism", "")
        validation = self.validator.validate_text(text, result["core_properties"])

        return {
            "all_core_satisfied": len(validation["missing"]) == 0,
            "satisfied": validation["satisfied"],
            "missing": validation["missing"],
            "emergent_detected": validation["emergent"],
            "confidence": len(validation["satisfied"]) / max(len(result["core_properties"]), 1),
        }

    def get_emergent_report(self, result: Dict) -> str:
        """生成涌现属性分析报告"""
        is_paradox = result.get("is_paradoxical", False)
        contradictions = result.get("contradictions", [])

        header = "悖论造物涌现分析报告" if is_paradox else "造物涌现分析报告"
        lines = [
            "=" * 50,
            header,
            f"造物: {result['name']}",
            "=" * 50,
            "",
        ]

        # 矛盾信息
        if is_paradox and contradictions:
            lines.append(f"⚔ 检测到 {len(contradictions)} 对核心矛盾：")
            for prop_a, prop_b, _ in contradictions:
                lines.append(f"  ⚔ {prop_a} ⟷ {prop_b}")
            lines.append("")

        lines.append(f"📋 核心属性（指定 {len(result['core_properties'])} 条）：")
        paradoxical_props = set()
        for a, b, _ in contradictions:
            paradoxical_props.add(a)
            paradoxical_props.add(b)
        for prop in result["core_properties"]:
            if prop in paradoxical_props:
                lines.append(f"  ⚔ {prop}  （矛盾属性）")
            else:
                lines.append(f"  ✅ {prop}")

        lines.append("")
        if result.get("emergent_properties"):
            pool_label = "破坏性涌现" if is_paradox else "涌现"
            lines.append(f"✨ {pool_label}属性（自发产生 {len(result['emergent_properties'])} 条）：")
            for prop in result["emergent_properties"]:
                lines.append(f"  ⚡ {prop}")
        else:
            lines.append("✨ 涌现属性：无（造物尚未发展出额外特性）")

        lines.append("")
        lines.append(f"📊 满足度: {result['validation']['confidence']:.0%}")
        lines.append(f"   核心属性满足: {len(result['validation']['satisfied'])}/{len(result['core_properties'])}")

        if result.get("archetypes"):
            lines.append("")
            lines.append(f"🎨 存在形式原型：")
            for i, archetype in enumerate(result["archetypes"]):
                lines.append(f"  属性「{result['core_properties'][i]}」→ 原型「{archetype}」")

        lines.append("")
        lines.append(f"🌌 总属性数: {len(result['all_properties'])} 条")
        lines.append("=" * 50)
        return "\n".join(lines)

    def list_history(self) -> List[Dict]:
        """获取历史造物列表"""
        return [
            {
                "index": i + 1,
                "name": h["name"],
                "core": h["core_properties"],
                "emergent": h["emergent_properties"],
                "time": h["timestamp"],
            }
            for i, h in enumerate(self.history)
        ]

    def get_library(self) -> Dict:
        """获取可用属性库"""
        return self.validator.library
